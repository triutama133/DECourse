// Builds app/js/py-challenges-data.js from curriculum/python-challenges/{en,id}.md.
//   node scripts/build-challenges.js          write the file
//   node scripts/build-challenges.js --check  only validate (ids, order, levels and drill syntax must match in both languages)
const fs = require("fs");
const path = require("path");
const DrillParse = require("../app/js/drill-parse.js");
const dir = path.join(__dirname, "../curriculum/python-challenges");
const parse = (lang) => {
  const text = fs.readFileSync(path.join(dir, lang + ".md"), "utf8").replace(/\r\n/g, "\n");
  const out = [];
  const re = /^## @challenge (\S+) \| (\d) \| ([^\n]+)\n([\s\S]*?)(?=^## @challenge |\s*$(?![\s\S]))/gm;
  let m;
  while ((m = re.exec(text))) out.push({ id: m[1], level: Number(m[2]), topic: m[3].trim(), block: m[4].trim() });
  return out;
};
const en = parse("en"), id = parse("id");
let bad = 0;
const fail = (msg) => { bad++; console.log("FAIL " + msg); };
if (en.length !== id.length) fail(`English has ${en.length} challenges, Indonesian ${id.length}`);
const seen = new Set();
en.forEach((c, i) => {
  const o = id[i];
  if (!o || o.id !== c.id) fail(`position ${i + 1}: ${c.id} (en) vs ${o && o.id} (id)`);
  else if (o.level !== c.level) fail(`${c.id}: level differs`);
  if (seen.has(c.id)) fail(`${c.id}: duplicate id`);
  seen.add(c.id);
  for (const [lang, x] of [["en", c], ["id", o]]) {
    if (!x) continue;
    const d = DrillParse.parse(x.block);
    if (!d || d.lang !== "python") fail(`${c.id} (${lang}): not a python drill`);
    else if (!d.checks.length || !d.solution || !d.starter) fail(`${c.id} (${lang}): needs @starter, @check and @solution`);
    else if (o && o.id === c.id) {
      const e = DrillParse.parse(c.block);
      if (e.checks.length !== d.checks.length) fail(`${c.id}: ${e.checks.length} checks in en, ${d.checks.length} in id`);
    }
  }
});
if (bad) process.exit(1);
const data = en.map((c, i) => ({ id: c.id, level: c.level, topic: { en: c.topic, id: id[i].topic }, block: { en: c.block, id: id[i].block } }));
const body = "/* GENERATED by scripts/build-challenges.js from curriculum/python-challenges. Do not edit by hand. */\nwindow.PY_CHALLENGES = " + JSON.stringify(data) + ";\n";
const target = path.join(__dirname, "../app/js/py-challenges-data.js");
if (process.argv.includes("--check")) {
  if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== body) { console.log("FAIL app/js/py-challenges-data.js is out of date: run node scripts/build-challenges.js"); process.exit(1); }
  console.log(`${data.length} Python challenges, in sync`);
} else {
  fs.writeFileSync(target, body);
  console.log(`wrote app/js/py-challenges-data.js: ${data.length} challenges (${Math.round(body.length / 1024)} KB)`);
}
